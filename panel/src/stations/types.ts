/** Что колонка делает сейчас: рисунок показывает это кольцом и своей анимацией. */
export type StationStage = 'idle' | 'listen' | 'think' | 'speak';

/**
 * Входы любого рисунка колонок — одни на все модели, поэтому дашборд не знает, какая модель нарисована.
 * Новая модель — её корпус в models.tsx и строка в реестре (index.ts).
 */
export interface StationArtProps {
    /** Цвет корпуса из тех, что знает рисунок; незнакомый — его первый. */
    skin?: string;
    /** Вариант с часами на корпусе (у Лайт 2 есть и без них); по умолчанию — с часами. */
    clock?: boolean;
    /** Наклейка-котик на фасаде (у Лайт 2 они лежат в коробке); у моделей без наклеек не рисуется. */
    sticker?: boolean;
    /** Цвет кольца — кто сейчас отвечает: CSS-цвет или var(--bar-own) и подобные. */
    ring: string;
    stage: StationStage;
    /** Колонка не в сети: кольцо не дышит. */
    offline?: boolean;
    /** Часовой пояс колонки (из её синхронизации): часы на корпусе идут по её времени, без него — по браузеру. */
    timeZone?: string;
}

/** Значок колонки в шапке и списке — её силуэт в цвете корпуса. */
export interface StationGlyphProps {
    color?: string | null;
    size?: number;
}
