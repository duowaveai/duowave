/// «Нужен ключ Todoist», «Нужна ссылка iCal», «Нужны: ключ Todoist, ссылка iCal»: the first word's ending picks the
/// form.
fn needs(titles: &[String]) -> String {
    let lower = |title: &str| -> String {
        let mut chars = title.trim().chars();
        chars.next().map(|first| first.to_lowercase().chain(chars).collect()).unwrap_or_default()
    };
    match titles {
        [] => String::new(),
        [one] => {
            let first = one.split_whitespace().next().unwrap_or_default().to_lowercase();
            let form = if first.ends_with("мя") || first.ends_with('о') || first.ends_with('е') {
                "Нужно"
            } else if first.ends_with('а') || first.ends_with('я') {
                "Нужна"
            } else {
                "Нужен"
            };
            format!(" {form} {}.", lower(one))
        }
        many => format!(" Нужны: {}.", many.iter().map(|title| lower(title)).collect::<Vec<_>>().join(", ")),
    }
}

/// 1, 21, 31 — «секунду»; 2–4, 22–24 — «секунды»; the rest, 11–14 too — «секунд».
fn plural(n: u64) -> usize {
    match (n % 10, n % 100) {
        (_, 11..=14) => 2,
        (1, _) => 0,
        (2..=4, _) => 1,
        _ => 2,
    }
}
