#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reads_five_passages_of_a_calm_minute_or_less() {
        for passage in PASSAGES {
            let words = passage.split_whitespace().count();
            assert!((60..=110).contains(&words), "{words} words: {passage}");
            assert!(!passage.contains("  "), "joined lines keep one space: {passage}");
            assert!(!passage.chars().any(|c| c.is_ascii_digit()), "numbers are spelled out: {passage}");
        }
    }
}
