/// «It needs the Todoist key.», «It needs: the Todoist key, the iCal link.».
fn needs(titles: &[String]) -> String {
    match titles {
        [] => String::new(),
        [one] => format!(" It needs {}.", one.trim()),
        many => format!(" It needs: {}.", many.iter().map(|title| title.trim()).collect::<Vec<_>>().join(", ")),
    }
}

/// 1 — «second»; the rest — «seconds».
fn plural(n: u64) -> usize {
    if n == 1 {
        0
    } else {
        2
    }
}
